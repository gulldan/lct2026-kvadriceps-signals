-- Дата публикации лежала только в паспорте источника, а колонка оставалась
-- пустой: 20 481 документ из 21 601 с паспортом. Индекс темы читает годы из
-- колонки, поэтому 580 тем из 809 не попадали на карту — «нет данных о
-- свежести» при том, что дата была известна с самого сбора. Паспорт типизирован
-- и проверен при записи, разобранная из файла дата — нет, поэтому заполняем
-- только пустое и ничего не переписываем.
UPDATE documents
SET published_at = source_metadata -> 'publication' ->> 'value'
WHERE published_at = ''
  AND source_metadata -> 'publication' ->> 'value' IS NOT NULL
  AND source_metadata -> 'publication' ->> 'value' <> '';

