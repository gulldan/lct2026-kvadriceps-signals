-- снова приходили без неё: 25.09 пустая колонка стояла у 2 383 документов с
-- паспортом (патенты 982, Crossref 920, arXiv 247, веб 234), и радар считал их
-- загруженными в день сбора. У 992 работ arXiv в колонке — docinfo PDF, день
-- сборки файла. Паспорт типизирован и проверен при записи, поэтому его дата
-- теперь главная; строки, где день и так совпадает, не трогаются.
UPDATE documents
SET published_at = source_metadata -> 'publication' ->> 'value'
WHERE coalesce(source_metadata -> 'publication' ->> 'value', '') <> ''
  AND left(published_at, 10) IS DISTINCT FROM left(source_metadata -> 'publication' ->> 'value', 10);

